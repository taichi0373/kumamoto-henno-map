-- 既存DB向けマイグレーション: USERS に最終ログイン日時・IPアドレスを追加
-- 新規構築時は DDL/TABLE/USERS.SQL に含まれるため実行不要
-- 実行例: psql -U <user> -d <db> -f config/database/MIGRATION/20261025_USERS_ADD_LAST_LOGIN.SQL
ALTER TABLE USERS ADD COLUMN IF NOT EXISTS LAST_LOGIN_AT TIMESTAMP;
ALTER TABLE USERS ADD COLUMN IF NOT EXISTS LAST_LOGIN_IP VARCHAR(45);

COMMENT ON COLUMN USERS.LAST_LOGIN_AT IS '最終ログイン日時';
COMMENT ON COLUMN USERS.LAST_LOGIN_IP IS '最終ログインIPアドレス';
