CREATE TABLE EMAIL_VERIFICATION_TOKENS (
  TOKEN_ID               BIGSERIAL PRIMARY KEY,
  USER_ID                BIGINT NOT NULL,
  TOKEN                  VARCHAR(64) NOT NULL,
  NEW_EMAIL              VARCHAR(200),
  EXPIRES_AT             TIMESTAMP NOT NULL,
  USED                   BOOLEAN DEFAULT FALSE NOT NULL,
  SYS_CREATED_AT         TIMESTAMP,
  SYS_UPDATED_AT         TIMESTAMP,
  CONSTRAINT EMAIL_VERIFICATION_TOKENS_TOKEN_UNIQUE UNIQUE (TOKEN),
  CONSTRAINT EMAIL_VERIFICATION_TOKENS_FK FOREIGN KEY (USER_ID) REFERENCES USERS (USER_ID) ON DELETE CASCADE
);

CREATE INDEX EMAIL_VERIFICATION_TOKENS_USER_ID_IDX ON EMAIL_VERIFICATION_TOKENS (USER_ID);

COMMENT ON TABLE EMAIL_VERIFICATION_TOKENS IS 'メールアドレス確認トークンテーブル';
COMMENT ON COLUMN EMAIL_VERIFICATION_TOKENS.TOKEN_ID IS 'トークンID';
COMMENT ON COLUMN EMAIL_VERIFICATION_TOKENS.USER_ID IS 'ユーザーID';
COMMENT ON COLUMN EMAIL_VERIFICATION_TOKENS.TOKEN IS '確認トークン（SHA-256ハッシュ）';
COMMENT ON COLUMN EMAIL_VERIFICATION_TOKENS.NEW_EMAIL IS '変更後メールアドレス（NULL:新規登録時の確認）';
COMMENT ON COLUMN EMAIL_VERIFICATION_TOKENS.EXPIRES_AT IS '有効期限';
COMMENT ON COLUMN EMAIL_VERIFICATION_TOKENS.USED IS '使用済みフラグ';
COMMENT ON COLUMN EMAIL_VERIFICATION_TOKENS.SYS_CREATED_AT IS '作成日時';
COMMENT ON COLUMN EMAIL_VERIFICATION_TOKENS.SYS_UPDATED_AT IS '更新日時';
