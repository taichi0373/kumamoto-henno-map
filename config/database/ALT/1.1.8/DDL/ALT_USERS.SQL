-- 既存DB向けALT: USERS に最終ログイン日時・IPアドレスを追加
-- カラム順を DDL/TABLE/USERS.SQL と揃えるため、バックアップ取得 → 再作成 → データ移行 の手順で行う
-- 新規構築時は DDL/TABLE/USERS.SQL に含まれるため実行不要
-- 実行例: psql -U <user> -d <db> -f config/database/ALT/1.1.8/DDL/ALT_USERS.SQL
\set ON_ERROR_STOP on

BEGIN;

-- バックアップ取得〜再作成の間に書き込まれた行が失われないよう、先に排他ロックを取得
LOCK TABLE USERS, PASSWORD_RESET_TOKENS, REFRESH_TOKENS IN ACCESS EXCLUSIVE MODE;

-- バックアップ取得
CREATE TABLE USERS_BK AS SELECT * FROM USERS;

-- USERS を参照する外部キーを一時的に削除
ALTER TABLE PASSWORD_RESET_TOKENS DROP CONSTRAINT PASSWORD_RESET_TOKENS_FK;
ALTER TABLE REFRESH_TOKENS DROP CONSTRAINT REFRESH_TOKENS_FK;

-- テーブル再作成
DROP TABLE USERS;

CREATE TABLE USERS (
  USER_ID                BIGSERIAL PRIMARY KEY,
  USERNAME               VARCHAR(30) NOT NULL,
  PASSWORD_HASH          VARCHAR(200) NOT NULL,
  EMAIL                  VARCHAR(200) NOT NULL,
  BIRTH_DATE             DATE,
  MUNICIPALITY_CD      VARCHAR(6),
  LICENSE_STATUS         VARCHAR(1),
  LICENSE_SURRENDERED_AT DATE,
  IS_ADMIN               CHAR(1) DEFAULT '0' NOT NULL,
  SYS_CREATED_AT         TIMESTAMP,
  SYS_UPDATED_AT         TIMESTAMP,
  LAST_LOGIN_AT          TIMESTAMP,
  LAST_LOGIN_IP          VARCHAR(45),
  CONSTRAINT USERS_USERNAME_UNIQUE UNIQUE (USERNAME),
  CONSTRAINT USERS_EMAIL_UNIQUE UNIQUE (EMAIL),
  CONSTRAINT USERS_FK FOREIGN KEY (MUNICIPALITY_CD) REFERENCES MUNICIPALITY (MUNICIPALITY_CD)
);

COMMENT ON TABLE USERS IS 'ユーザーテーブル';
COMMENT ON COLUMN USERS.USER_ID IS 'ユーザーID';
COMMENT ON COLUMN USERS.USERNAME IS 'ユーザー名';
COMMENT ON COLUMN USERS.PASSWORD_HASH IS 'パスワード';
COMMENT ON COLUMN USERS.EMAIL IS 'メールアドレス';
COMMENT ON COLUMN USERS.BIRTH_DATE IS '生年月日';
COMMENT ON COLUMN USERS.MUNICIPALITY_CD IS '自治体コード';
COMMENT ON COLUMN USERS.LICENSE_STATUS IS '運転免許所持状況';
COMMENT ON COLUMN USERS.LICENSE_SURRENDERED_AT IS '運転免許返納日';
COMMENT ON COLUMN USERS.IS_ADMIN IS '管理者フラグ（1:管理者,0:一般ユーザー）';
COMMENT ON COLUMN USERS.SYS_CREATED_AT IS '作成日時';
COMMENT ON COLUMN USERS.SYS_UPDATED_AT IS '更新日時';
COMMENT ON COLUMN USERS.LAST_LOGIN_AT IS '最終ログイン日時';
COMMENT ON COLUMN USERS.LAST_LOGIN_IP IS '最終ログインIPアドレス';

-- データ移行（追加カラムは NULL）
INSERT INTO USERS (
  USER_ID,
  USERNAME,
  PASSWORD_HASH,
  EMAIL,
  BIRTH_DATE,
  MUNICIPALITY_CD,
  LICENSE_STATUS,
  LICENSE_SURRENDERED_AT,
  IS_ADMIN,
  SYS_CREATED_AT,
  SYS_UPDATED_AT
)
SELECT
  USER_ID,
  USERNAME,
  PASSWORD_HASH,
  EMAIL,
  BIRTH_DATE,
  MUNICIPALITY_CD,
  LICENSE_STATUS,
  LICENSE_SURRENDERED_AT,
  IS_ADMIN,
  SYS_CREATED_AT,
  SYS_UPDATED_AT
FROM USERS_BK;

-- 旧マイグレーション（ADD COLUMN）適用済みの環境では、既存の最終ログイン情報を引き継ぐ
DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS
    WHERE TABLE_SCHEMA = CURRENT_SCHEMA() AND TABLE_NAME = 'users_bk' AND COLUMN_NAME = 'last_login_at'
  ) THEN
    EXECUTE 'UPDATE USERS U SET LAST_LOGIN_AT = B.LAST_LOGIN_AT, LAST_LOGIN_IP = B.LAST_LOGIN_IP FROM USERS_BK B WHERE U.USER_ID = B.USER_ID';
  END IF;
END
$$;

-- シーケンスを移行後の最大値に合わせる
SELECT SETVAL(PG_GET_SERIAL_SEQUENCE('users', 'user_id'), COALESCE(MAX(USER_ID), 1), MAX(USER_ID) IS NOT NULL) FROM USERS;

-- 外部キーを再作成
ALTER TABLE PASSWORD_RESET_TOKENS ADD CONSTRAINT PASSWORD_RESET_TOKENS_FK FOREIGN KEY (USER_ID) REFERENCES USERS (USER_ID) ON DELETE CASCADE;
ALTER TABLE REFRESH_TOKENS ADD CONSTRAINT REFRESH_TOKENS_FK FOREIGN KEY (USER_ID) REFERENCES USERS (USER_ID) ON DELETE CASCADE;

COMMIT;

